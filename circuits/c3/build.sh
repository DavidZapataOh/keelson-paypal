#!/usr/bin/env bash
# Compiles the circuit and writes what the prover, the verifiers and the contracts pin: the ACIR
# program, its verification key and the Solidity verifiers. Needs nargo, bb and jq on PATH.
set -euo pipefail
cd "$(dirname "$0")"
verifiers=../../contracts/src/verifiers

nargo compile --silence-warnings
# Debug symbols and the file map carry local paths: the prover needs the program and its ABI only.
jq -c '{noir_version, hash, abi, bytecode}' target/anonymous_mandate.json >../../services/api/zk/anonymous_mandate.json
bb write_vk -b target/anonymous_mandate.json -o target -t evm
cp target/vk anonymous_mandate.vk
bb write_solidity_verifier -k target/vk -t evm --optimized -o "$verifiers/AnonymousMandateVerifier.sol"
bb write_solidity_verifier -k target/vk -t evm -o "$verifiers/AnonymousMandateReferenceVerifier.sol"
{
  echo "// Generated by circuits/c3/build.sh. Do not edit."
  echo
  echo "/** The C3 \`anonymous_mandate\` UltraHonk verification key for the EVM target, standard base64. */"
  echo "export const C3_VERIFICATION_KEY ="
  echo "  \"$(base64 <target/vk | tr -d '\n')\";"
} >../../packages/alibi/src/verify/c3-vk.ts
