#!/usr/bin/env bash
# Pins the C1 and C3 recursive keys, compiles the circuit and writes what the prover, the verifiers
# and the contracts pin: the ACIR program, its verification key and the Solidity verifiers. Run
# circuits/c1/build.sh and circuits/c3/build.sh first. Needs nargo, bb and jq on PATH.
set -euo pipefail
cd "$(dirname "$0")"
zk=../../services/api/zk
verifiers=../../contracts/src/verifiers

{
  echo "// Generated by circuits/c1c3/build.sh from the circuits' recursive keys. Do not edit."
  echo
  echo "pub global C1_KEY_HASH: Field = $(jq -r .hash "$zk/mandate_predicate.recursive.json");"
  echo "pub global C3_KEY_HASH: Field = $(jq -r .hash "$zk/anonymous_mandate.recursive.json");"
} >src/keys.nr
nargo compile --silence-warnings
jq -c '{noir_version, hash, abi, bytecode}' target/anonymous_purchase.json >"$zk/anonymous_purchase.json"
bb write_vk -b target/anonymous_purchase.json -o target -t evm
cp target/vk anonymous_purchase.vk
bb write_solidity_verifier -k target/vk -t evm --optimized -o "$verifiers/AnonymousPurchaseVerifier.sol"
bb write_solidity_verifier -k target/vk -t evm -o "$verifiers/AnonymousPurchaseReferenceVerifier.sol"
{
  echo "// Generated by circuits/c1c3/build.sh. Do not edit."
  echo
  echo "/** The \`anonymous_purchase\` (C1 composed with C3) UltraHonk verification key for the EVM target, standard base64. */"
  echo "export const C1C3_VERIFICATION_KEY ="
  echo "  \"$(base64 <target/vk | tr -d '\n')\";"
} >../../packages/alibi/src/verify/c1c3-vk.ts
