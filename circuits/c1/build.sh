#!/usr/bin/env bash
# Compiles the circuit and writes what the engine, the verifier and the contracts pin: the ACIR
# program, its verification keys and the Solidity verifiers. Needs nargo, bb and jq on PATH.
set -euo pipefail
cd "$(dirname "$0")"
out=../../engine/tee/zk
verifiers=../../contracts/src/verifiers

nargo compile --silence-warnings
# Debug symbols and the file map carry local paths: the engine needs the program and its ABI only.
jq -c '{noir_version, hash, abi, bytecode}' target/mandate_predicate.json >"$out/mandate_predicate.json"
bb write_vk -b target/mandate_predicate.json -o target -t evm
cp target/vk "$out/mandate_predicate.vk"
# The key for recursion, binary for the engine and as fields with its hash for the composing circuit.
bb write_vk -b target/mandate_predicate.json -o target/recursive -t noir-recursive
cp target/recursive/vk "$out/mandate_predicate.recursive.vk"
bb write_vk -b target/mandate_predicate.json -o target/recursive -t noir-recursive --output_format json
jq -c '{vk, hash}' target/recursive/vk.json >../../services/api/zk/mandate_predicate.recursive.json
mkdir -p "$verifiers"
bb write_solidity_verifier -k target/vk -t evm --optimized -o "$verifiers/MandatePredicateVerifier.sol"
bb write_solidity_verifier -k target/vk -t evm -o "$verifiers/MandatePredicateReferenceVerifier.sol"
{
  echo "// Generated by circuits/c1/build.sh. Do not edit."
  echo
  echo "/** The C1 \`mandate_predicate\` UltraHonk verification key for the EVM target, standard base64. */"
  echo "export const C1_VERIFICATION_KEY ="
  echo "  \"$(base64 <target/vk | tr -d '\n')\";"
} >../../packages/alibi/src/verify/c1-vk.ts
