/**
 * Copies the Cedar policy set and schema from `engine/policy/policy` into
 * `src/generated/policy.ts`, so the TS evaluator runs the exact bytes the Rust engine hashes.
 */
import { readFileSync, writeFileSync } from "node:fs";

const source = new URL("../../../engine/policy/policy/", import.meta.url);
const read = (name: string) => readFileSync(new URL(name, source), "utf8");

const out = `// Generated by scripts/embed.ts from engine/policy/policy. Do not edit.

/** The policy set source, \`keelson.cedar\`. */
export const POLICY_SET_SRC: string =
  ${JSON.stringify(read("keelson.cedar"))};

/** The schema source, \`keelson.cedarschema\`. */
export const SCHEMA_SRC: string =
  ${JSON.stringify(read("keelson.cedarschema"))};
`;

writeFileSync(new URL("../src/generated/policy.ts", import.meta.url), out);
