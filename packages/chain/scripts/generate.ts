import { execFileSync } from "node:child_process";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { getAddress } from "viem";

const chainIds = [421614, 42161, 11155111] as const;
const contracts = new URL("../../../contracts/", import.meta.url);
const src = new URL("../src/", import.meta.url);

interface Registry {
  contracts: Record<string, string>;
}

interface Artifact {
  abi: unknown[];
  metadata?: { settings?: { compilationTarget?: Record<string, string> } };
}

const registries = chainIds.map(
  (id) =>
    JSON.parse(readFileSync(new URL(`deployments/${id}.json`, contracts), "utf8")) as Registry,
);
const deployed = new Set(registries.flatMap((r) => Object.keys(r.contracts)));

// Every contract under contracts/src, plus the library contracts the registry deploys (governance).
const abis = new Map<string, unknown[]>();
const out = new URL("out/", contracts);
for (const dir of readdirSync(out)) {
  if (!dir.endsWith(".sol")) continue;
  for (const file of readdirSync(new URL(`${dir}/`, out))) {
    const artifact = JSON.parse(readFileSync(new URL(`${dir}/${file}`, out), "utf8")) as Artifact;
    const [path, name] =
      Object.entries(artifact.metadata?.settings?.compilationTarget ?? {})[0] ?? [];
    if (path === undefined || name === undefined || artifact.abi.length === 0) continue;
    if (path.startsWith("src/") || (path.startsWith("lib/") && deployed.has(name))) {
      abis.set(name, artifact.abi);
    }
  }
}

const header =
  "// Generated by scripts/generate.ts from forge build artifacts and contracts/deployments. Do not edit.\n";
const camel = (name: string) => name[0]?.toLowerCase() + name.slice(1);

const abisFile = new URL("abis.ts", src);
writeFileSync(
  abisFile,
  header +
    [...abis.keys()]
      .sort()
      .map(
        (name) => `export const ${camel(name)}Abi = ${JSON.stringify(abis.get(name))} as const;\n`,
      )
      .join("\n"),
);

const addressesFile = new URL("addresses.ts", src);
const byChain = chainIds.map((id, i) => {
  const entries = Object.entries(registries[i]?.contracts ?? {})
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([name, address]) => `${JSON.stringify(name)}: ${JSON.stringify(getAddress(address))}`);
  return `${id}: {${entries.join(",")}}`;
});
writeFileSync(
  addressesFile,
  `${header}import type { Address } from "viem";

export const chainIds = ${JSON.stringify(chainIds)} as const;

export type ChainId = (typeof chainIds)[number];

export const addresses: Record<ChainId, Readonly<Record<string, Address>>> = {${byChain.join(",")}};
`,
);

execFileSync("biome", ["format", "--write", abisFile.pathname, addressesFile.pathname], {
  stdio: "inherit",
});
