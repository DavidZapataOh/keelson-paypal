/**
 * Writes the inputs of the C2b `amber_contradiction` circuit: one prover file per amber field
 * (`circuits/c2b/Prover_<field>.toml`), each a false attestation about the demo store's Tempo 3 in
 * size 11, and the circuit's Noir test vectors.
 *
 * With `<case.json> <name>`, writes `Prover_<name>.toml` for a real session instead: the case holds
 * the prover's answer for the session (`url`, `committed`, `blinder`), the attested `amber`
 * (`unitMinor` as a decimal string), its `salt` and the contradicted `field`.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  AMBER_FIELDS,
  type Amber,
  amberCommitment,
  amberProduct,
  packAmberString,
} from "../src/amber.ts";

const here = dirname(fileURLToPath(import.meta.url));
const circuit = resolve(here, "../../../circuits/c2b");
const MAX_RANGE = 512;

const hex = (x: bigint) => `0x${x.toString(16).padStart(64, "0")}`;

interface Case {
  url: URL;
  range: Uint8Array;
  blinder: Uint8Array;
  amber: Amber;
  salt: bigint;
  field: keyof typeof AMBER_FIELDS;
}

async function inputs(c: Case) {
  if (c.range.length > MAX_RANGE || c.blinder.length !== 16) throw new RangeError("range");
  const digest = createHash("sha256").update(c.range).update(c.blinder).digest("hex");
  const product = amberProduct(c.url);
  const padded = [...c.range, ...Array(MAX_RANGE - c.range.length).fill(0)];
  return {
    range_hi: `0x${digest.slice(0, 32)}`,
    range_lo: `0x${digest.slice(32)}`,
    amber_commitment: hex(await amberCommitment(product, c.amber, c.salt)),
    product: hex(product),
    field_id: String(AMBER_FIELDS[c.field]),
    range: padded.map(String),
    range_len: String(c.range.length),
    blinder: [...c.blinder].map(String),
    salt: hex(c.salt),
    amber: {
      sku: hex(packAmberString(c.amber.sku)),
      size: hex(packAmberString(c.amber.size)),
      color: hex(packAmberString(c.amber.color)),
      unit_minor: String(c.amber.unitMinor),
      returns_free: c.amber.returnsFree ? "1" : "0",
    },
  };
}

const toml = (key: string, v: unknown): string =>
  Array.isArray(v) ? `${key} = [${v.map((x) => `"${x}"`).join(", ")}]` : `${key} = "${v}"`;

async function write(name: string, c: Case): Promise<Awaited<ReturnType<typeof inputs>>> {
  const { amber, ...top } = await inputs(c);
  writeFileSync(
    resolve(circuit, `Prover_${name}.toml`),
    `${[
      ...Object.entries(top).map(([k, v]) => toml(k, v)),
      "",
      "[amber]",
      ...Object.entries(amber).map(([k, v]) => toml(k, v)),
    ].join("\n")}\n`,
  );
  return { amber, ...top };
}

const [casePath, caseName] = process.argv.slice(2);
if (casePath && caseName) {
  const j = JSON.parse(readFileSync(casePath, "utf8"));
  await write(caseName, {
    url: new URL(j.url),
    range: Buffer.from(j.committed, "hex"),
    blinder: Buffer.from(j.blinder, "hex"),
    amber: { ...j.amber, unitMinor: BigInt(j.amber.unitMinor) },
    salt: BigInt(j.salt),
    field: j.field,
  });
} else {
  const url = new URL("https://store.keelson.finance/api/products/tempo-3");
  const range = new TextEncoder().encode(
    '{"sku":"RF-TMP3-11","size":"11","color":"blue","unit_minor":12900,"returns_free":true}',
  );
  const blinder = Uint8Array.from({ length: 16 }, (_, i) => 0x10 + i);
  const salt = 0x0a3b3e5c1d2f40516273849506a7b8c9n;
  const honest: Amber = {
    sku: "RF-TMP3-11",
    size: "11",
    color: "blue",
    unitMinor: 12900n,
    returnsFree: true,
  };
  const falsehoods: Record<keyof typeof AMBER_FIELDS, Partial<Amber>> = {
    size: { size: "10" },
    color: { color: "red" },
    unitPrice: { unitMinor: 11900n },
    returnsFree: { returnsFree: false },
  };
  const written: Record<string, Awaited<ReturnType<typeof inputs>>> = {};
  for (const [field, lie] of Object.entries(falsehoods)) {
    written[field] = await write(field, {
      url,
      range,
      blinder,
      amber: { ...honest, ...lie },
      salt,
      field: field as keyof typeof AMBER_FIELDS,
    });
  }
  const size = written.size;
  if (!size) throw new Error("no size case");
  const nr = (k: string, v: string, t: string) => `pub global ${k}: ${t} = ${v};`;
  writeFileSync(
    resolve(circuit, "src/vectors.nr"),
    `${[
      "// Generated by packages/core/scripts/c2b-vectors.ts. Do not edit.",
      "",
      nr("PRODUCT", size.product, "Field"),
      nr("SALT", size.salt, "Field"),
      nr("SKU", size.amber.sku, "Field"),
      nr("SIZE_10", size.amber.size, "Field"),
      nr("COLOR", size.amber.color, "Field"),
      nr("AMBER_SIZE_10", size.amber_commitment, "Field"),
      nr("RANGE_HI", size.range_hi, "Field"),
      nr("RANGE_LO", size.range_lo, "Field"),
    ].join("\n")}\n`,
  );
}
