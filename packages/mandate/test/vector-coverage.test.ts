import { existsSync, readdirSync, readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, test } from "vitest";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
const read = (path: string) => readFileSync(resolve(root, path), "utf8");

/** Globals whose value TypeScript computes and the circuit's tests rely on. */
const COMPUTED = /^(C_M|.*ROOT|.*HASH|.*COMMITMENT|PRODUCT|SKU)/;

/** Values only TypeScript and Noir compute, each with the reason the engine does not. */
const TS_AND_NOIR_ONLY: Record<string, string> = {
  "c1/CART_HASH": "a fixed demo cart digest: an input of the circuit that nothing computes",
  "c2b/PRODUCT": "the amber product commitment is built by the API's TypeScript, never the engine",
  "c2b/SKU": "the amber SKU field is built by the API's TypeScript, never the engine",
  "c3/USER_SET_ROOT": "the registered-user tree is built by the API's TypeScript, never the engine",
};

const circuits = readdirSync(resolve(root, "circuits")).filter((c) =>
  existsSync(resolve(root, "circuits", c, "src/vectors.nr")),
);

/** Every Rust test source, with the files its `include_str!` reads, as repo-relative paths. */
const rustTests = readdirSync(resolve(root, "engine"))
  .map((crate) => `engine/${crate}/tests`)
  .filter((dir) => existsSync(resolve(root, dir)))
  .flatMap((dir) =>
    readdirSync(resolve(root, dir))
      .filter((f) => f.endsWith(".rs"))
      .map((f) => {
        const source = read(`${dir}/${f}`);
        const includes = [...source.matchAll(/include_str!\(\s*"([^"]+)"/g)].map((m) =>
          resolve(root, dir, m[1] as string).slice(root.length + 1),
        );
        return { source, includes };
      }),
  );

/** Every hex value in a JSON vector file a Rust test reads. */
const rustJsonValues = new Set(
  rustTests
    .flatMap((t) => t.includes)
    .filter((p) => p.endsWith(".json"))
    .flatMap((p) => [...read(p).matchAll(/"0x([0-9a-fA-F]{1,64})"/g)])
    .map((m) => BigInt(`0x${m[1]}`)),
);

describe("cross-language vectors", () => {
  test.each(circuits)("%s: each vectors.nr names a generator its package runs", (c) => {
    const header = read(`circuits/${c}/src/vectors.nr`).split("\n")[0] ?? "";
    const script = /^\/\/ Generated by (packages\/[^/]+)\/(scripts\/[\w-]+\.ts)\./.exec(header);
    expect(script, header).not.toBeNull();
    const [, pkg, path] = script as RegExpExecArray;
    const scripts = JSON.parse(read(`${pkg}/package.json`)).scripts as Record<string, string>;
    expect(scripts.vectors).toContain(path);
  });

  test("every value a circuit takes from TypeScript is recomputed by the engine's tests", () => {
    const unchecked: string[] = [];
    for (const c of circuits) {
      const path = `circuits/${c}/src/vectors.nr`;
      for (const m of read(path).matchAll(/^pub global (\w+): Field = (0x[0-9a-f]+);$/gm)) {
        const [, name, value] = m as unknown as [string, string, string];
        if (!COMPUTED.test(name)) continue;
        const inJson = rustJsonValues.has(BigInt(value));
        const named = rustTests.some(
          (t) => t.includes.includes(path) && t.source.includes(`"${name}"`),
        );
        if (!inJson && !named && !(`${c}/${name}` in TS_AND_NOIR_ONLY)) {
          unchecked.push(`${c}/${name}`);
        }
      }
    }
    expect(unchecked).toEqual([]);
  });

  test("the composed circuit's inputs are generated from the inner proofs", () => {
    expect(read("circuits/c1c3/prove.sh")).toContain(">Prover.toml");
    expect(read("circuits/c1c3/.gitignore").split("\n")).toContain("Prover.toml");
  });
});
