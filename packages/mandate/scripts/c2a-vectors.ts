/**
 * Writes the inputs of the C2a `mandate_violation` circuit for the demo mandate: one prover file
 * per violation class (`circuits/c2a/Prover_<class>.toml`) and the circuit's Noir test vectors.
 */
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { currencyNumeric } from "@keelson/core";
import {
  categoryMask,
  mandateCommitment,
  merchantLeaf,
  merchantMembership,
  merchantNonMembership,
  merchantTree,
  userKeyHash,
} from "../src/commitment.ts";
import { CATEGORY_TABLE, type Mandate, parseMandate } from "../src/schema.ts";
import demo from "../test/fixtures/demo-mandate.json" with { type: "json" };

const here = dirname(fileURLToPath(import.meta.url));
const circuit = resolve(here, "../../../circuits/c2a");

const m: Mandate = parseMandate(structuredClone(demo));
const salt = Uint8Array.from({ length: 16 }, (_, i) => i + 1);
const hex = (x: bigint) => `0x${x.toString(16).padStart(64, "0")}`;
const be = (bytes: Uint8Array) => BigInt(`0x${Buffer.from(bytes).toString("hex")}`);

const range = m.payment.constraints.find((c) => c.type === "payment.amount_range");
const merchants = m.checkout.constraints.find((c) => c.type === "checkout.allowed_merchants");
const category = m.checkout.constraints.find((c) => c.type === "keelson.category");
if (
  range?.type !== "payment.amount_range" ||
  merchants?.type !== "checkout.allowed_merchants" ||
  category?.type !== "keelson.category"
) {
  throw new Error("the demo mandate lacks a C2a constraint");
}
const memberId = merchants.allowed[0]?.id as string;
const outsiderId = "mrc_elsewhere";
const tree = await merchantTree(merchants.allowed.map((x) => x.id));
const member = await merchantMembership(tree, memberId);
const outsider = await merchantNonMembership(tree, outsiderId);
const euro = structuredClone(m);
euro.payment.currency = "EUR";
for (const c of euro.payment.constraints) if ("currency" in c) c.currency = "EUR";

/** The cart time of every class but expiry: inside the mandate's validity. */
const CART_TS = m.exp - 55_200;
const mandate = {
  user_key_hash: hex(await userKeyHash(m.user.cred.jwk)),
  max_amount: String(range.max),
  mandate_currency: String(currencyNumeric(m.payment.currency)),
  category_mask: String(categoryMask(category.allow) & ~categoryMask(category.deny)),
  merchant_root: hex(tree.root),
  expiry: String(m.exp),
  operator_id: m.agent.operator.agent_id,
  nonce: hex(be(Buffer.from(m.nonce, "base64url"))),
  salt: hex(be(salt)),
};
const cart = {
  c_m: hex(await mandateCommitment(m, salt)),
  amount: "8500",
  currency: String(currencyNumeric(m.payment.currency)),
  category: String(CATEGORY_TABLE.ids.indexOf(category.allow[0] as string)),
  merchant_id: hex(await merchantLeaf(memberId)),
  cart_ts: String(CART_TS),
};
const noLow = {
  value: hex(0n),
  next: hex(0n),
  next_index: "0",
  index: "0",
  path: Array(8).fill(hex(0n)),
};
const outsiderLow = {
  value: hex(outsider.low.value),
  next: hex(outsider.low.next),
  next_index: String(outsider.low.nextIndex),
  index: String(outsider.index),
  path: outsider.path.map(hex),
};

const classes = {
  amount: { ...cart, amount: String(range.max + 1), violation_code: "1" },
  currency: {
    ...cart,
    c_m: hex(await mandateCommitment(euro, salt)),
    violation_code: "2",
    mandate_currency: String(currencyNumeric("EUR")),
  },
  category: { ...cart, category: "6", violation_code: "3" },
  expiry: { ...cart, cart_ts: String(m.exp + 1), violation_code: "4" },
  merchant: { ...cart, merchant_id: hex(await merchantLeaf(outsiderId)), violation_code: "5" },
} as const;

const toml = (key: string, v: unknown): string =>
  Array.isArray(v) ? `${key} = [${v.map((x) => `"${x}"`).join(", ")}]` : `${key} = "${v}"`;
for (const [name, c] of Object.entries(classes)) {
  const inputs = { ...mandate, ...c };
  const low = name === "merchant" ? outsiderLow : noLow;
  const order = [
    "c_m",
    "amount",
    "currency",
    "category",
    "merchant_id",
    "cart_ts",
    "violation_code",
    ...Object.keys(mandate),
  ] as const;
  writeFileSync(
    resolve(circuit, `Prover_${name}.toml`),
    `${[
      ...order.map((k) => toml(k, (inputs as Record<string, string>)[k])),
      "",
      "[low]",
      ...Object.entries(low).map(([k, v]) => toml(k, v)),
    ].join("\n")}\n`,
  );
}

const nr = (k: string, v: string, t: string) => `pub global ${k}: ${t} = ${v};`;
writeFileSync(
  resolve(circuit, "src/vectors.nr"),
  `${[
    "// Generated by packages/mandate/scripts/c2a-vectors.ts. Do not edit.",
    "",
    nr("C_M", cart.c_m, "Field"),
    nr("C_M_EUR", classes.currency.c_m, "Field"),
    nr("AMOUNT", cart.amount, "u64"),
    nr("USD", cart.currency, "u16"),
    nr("EUR", classes.currency.mandate_currency, "u16"),
    nr("CATEGORY", cart.category, "u8"),
    nr("CART_TS", cart.cart_ts, "u64"),
    nr("USER_KEY_HASH", mandate.user_key_hash, "Field"),
    nr("MAX_AMOUNT", mandate.max_amount, "u64"),
    nr("CATEGORY_MASK", mandate.category_mask, "u64"),
    nr("MERCHANT_ROOT", mandate.merchant_root, "Field"),
    nr("EXPIRY", mandate.expiry, "u64"),
    nr("OPERATOR_ID", mandate.operator_id, "Field"),
    nr("NONCE", mandate.nonce, "Field"),
    nr("SALT", mandate.salt, "Field"),
    nr("MEMBER_ID", cart.merchant_id, "Field"),
    nr("MEMBER_INDEX", String(member.index), "u8"),
    nr("MEMBER_PATH", `[${member.path.map(hex).join(", ")}]`, "[Field; 8]"),
    nr("OUTSIDER_ID", classes.merchant.merchant_id, "Field"),
    nr("OUTSIDER_LOW_VALUE", outsiderLow.value, "Field"),
    nr("OUTSIDER_LOW_NEXT", outsiderLow.next, "Field"),
    nr("OUTSIDER_LOW_NEXT_INDEX", outsiderLow.next_index, "Field"),
    nr("OUTSIDER_LOW_INDEX", outsiderLow.index, "u8"),
    nr("OUTSIDER_LOW_PATH", `[${outsiderLow.path.join(", ")}]`, "[Field; 8]"),
  ].join("\n")}\n`,
);
