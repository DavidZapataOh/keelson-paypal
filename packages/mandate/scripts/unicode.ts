// Writes the Unicode control (Cc) and format (Cf) code point ranges, as this Node's ICU data
// defines them, to src/generated/unicode.ts and to the Rust engine, so both reject the same text.
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const version = process.versions.unicode;
const category = /^[\p{Cc}\p{Cf}]$/u;

const ranges: [number, number][] = [];
for (let c = 0; c <= 0x10ffff; c++) {
  if (c >= 0xd800 && c <= 0xdfff) continue;
  if (!category.test(String.fromCodePoint(c))) continue;
  const last = ranges.at(-1);
  if (last && last[1] === c - 1) last[1] = c;
  else ranges.push([c, c]);
}

const hex = (c: number) => `0x${c.toString(16)}`;
const rust = (c: number) => `'\\u{${c.toString(16)}}'`;
const doc = `Unicode ${version} general categories Cc (control) and Cf (format), as sorted inclusive code point ranges.`;

writeFileSync(
  resolve(root, "src/generated/unicode.ts"),
  `// Generated by scripts/unicode.ts. Do not edit.

/** ${doc} */
export const CONTROL_OR_FORMAT: readonly (readonly [number, number])[] = [
${ranges.map(([lo, hi]) => `  [${hex(lo)}, ${hex(hi)}],`).join("\n")}
];
`,
);

writeFileSync(
  resolve(root, "../../engine/mandate/src/unicode.rs"),
  `// Generated by packages/mandate/scripts/unicode.ts. Do not edit.

/// ${doc}
const CONTROL_OR_FORMAT: [(char, char); ${ranges.length}] = [
${ranges.map(([lo, hi]) => `    (${rust(lo)}, ${rust(hi)}),`).join("\n")}
];

/// Whether \`c\` is a control (Cc) or format (Cf) character.
pub(crate) fn is_control_or_format(c: char) -> bool {
    CONTROL_OR_FORMAT
        .iter()
        .take_while(|(lo, _)| *lo <= c)
        .any(|(_, hi)| c <= *hi)
}
`,
);
