/**
 * Writes the inputs of the C3 `anonymous_mandate` circuit: the demo mandate, held by a
 * deterministic test passkey, signed through Secure Payment Confirmation and plain WebAuthn with
 * the client data Chromium produced for the captured assertions, and a registered-user set of
 * three. Outputs the circuit's `Prover_payment.toml`, `Prover_webauthn.toml` and Noir test vectors (SPC),
 * a JSON vector the TypeScript witness builder is checked against, and C1's
 * `Prover_anonymous.toml` for a cart of the same mandate, which the composed circuit proves with it.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { p256 } from "@noble/curves/nist.js";
import { c3Inputs, userSet } from "../src/c3.ts";
import { hSd, mandateChallenge } from "../src/challenge.ts";
import { mandateCommitment, userKeyHash } from "../src/commitment.ts";
import { type Mandate, parseMandate } from "../src/schema.ts";
import { buildSdPayload } from "../src/sd.ts";
import demo from "../test/fixtures/demo-mandate.json" with { type: "json" };
import { c1Inputs, c1Toml } from "./c1-inputs.ts";

const here = dirname(fileURLToPath(import.meta.url));
const circuit = resolve(here, "../../../circuits/c3");
const captures = JSON.parse(
  readFileSync(resolve(here, "../test/vectors/webauthn-captures.json"), "utf8"),
) as {
  signed: Record<string, { assertion: { clientDataJSON: string; authenticatorData: string } }>;
};

const b64u = (b: Uint8Array): string => Buffer.from(b).toString("base64url");
const secret = createHash("sha256").update("keelson/vectors/c3/key").digest();
const point = p256.getPublicKey(secret, false);

const m: Mandate = parseMandate(structuredClone(demo));
m.user.cred.jwk = {
  ...m.user.cred.jwk,
  x: b64u(point.subarray(1, 33)),
  y: b64u(point.subarray(33)),
};
const salt = Uint8Array.from({ length: 16 }, (_, i) => i + 1);
const cm = await mandateCommitment(m, salt);
let counter = 0;
const { payloadSd, disclosures } = await buildSdPayload(
  { ...m, zk: { commitment: `0x${cm.toString(16).padStart(64, "0")}` } },
  () => createHash("sha256").update(`keelson/vectors/c3/sd/${counter++}`).digest().subarray(0, 16),
);
const challenge = b64u(mandateChallenge(hSd(payloadSd), cm));

/** A captured assertion's client data with this mandate's challenge, signed by the test key. */
function signed(capture: "payment" | "webauthn") {
  const a = captures.signed[capture]?.assertion;
  if (!a) throw new Error(`no ${capture} capture`);
  const data = JSON.parse(Buffer.from(a.clientDataJSON, "base64url").toString("utf8"));
  const clientData = Buffer.from(
    JSON.stringify({ ...data, challenge, origin: "https://app.keelson.finance" }),
  );
  const authData = Buffer.from(a.authenticatorData, "base64url");
  const digest = createHash("sha256").update(clientData).digest();
  const signature = p256.sign(Buffer.concat([authData, digest]), secret, {
    format: "der",
    lowS: false,
  });
  return {
    authenticatorData: b64u(authData),
    clientDataJSON: b64u(clientData),
    signature: b64u(signature),
  };
}

const others = [11n, 22n].map(
  (x) => BigInt(`0x${createHash("sha256").update(`u${x}`).digest("hex")}`) >> 8n,
);
const users = await userSet([
  others[0] as bigint,
  await userKeyHash(m.user.cred.jwk),
  others[1] as bigint,
]);

/** TOML of a Noir input map: each table's values, then its nested structs as `[a.b]` tables. */
function toml(table: object, path: string[] = []): string[] {
  const entries = Object.entries(table);
  const isTable = (x: unknown) => typeof x === "object" && x !== null && !Array.isArray(x);
  const value = (x: unknown) =>
    Array.isArray(x) ? `[${x.map((e) => `"${e}"`).join(", ")}]` : `"${x}"`;
  return [
    ...entries.filter(([, x]) => !isTable(x)).map(([k, x]) => `${k} = ${value(x)}`),
    ...entries
      .filter(([, x]) => isTable(x))
      .flatMap(([k, x]) => ["", `[${[...path, k].join(".")}]`, ...toml(x as object, [...path, k])]),
  ];
}

/** The SPC inputs as Noir globals, for the circuit's tests. */
function noirVectors(inputs: Record<string, unknown>): string {
  const i = inputs as {
    opening: Record<string, string>;
    assertion: Record<string, unknown> & { client_data_json: { storage: number[]; len: string } };
  } & Record<string, unknown>;
  const bytes = (v: unknown) => `[${(v as number[]).join(", ")}]`;
  const fields = (v: unknown) => `[${(v as string[]).join(", ")}]`;
  const lines = [
    "// Generated by packages/mandate/scripts/c3-vectors.ts. Do not edit.",
    "",
    `pub global C_M: Field = ${i.c_m};`,
    `pub global MANDATE_HASH: Field = ${i.mandate_hash};`,
    `pub global USER_SET_ROOT: Field = ${i.user_set_root};`,
    `pub global RP_ID_HASH: Field = ${i.rp_id_hash};`,
    `pub global KEY_X: [u8; 32] = ${bytes(i.key_x)};`,
    `pub global KEY_Y: [u8; 32] = ${bytes(i.key_y)};`,
    `pub global H_SD: [u8; 32] = ${bytes(i.h_sd)};`,
    `pub global USER_INDEX: u32 = ${i.user_index};`,
    `pub global USER_PATH: [Field; 20] = ${fields(i.user_path)};`,
    `pub global MAX_AMOUNT: u64 = ${i.opening.max_amount};`,
    `pub global CURRENCY: u16 = ${i.opening.currency};`,
    `pub global CATEGORY_MASK: u64 = ${i.opening.category_mask};`,
    `pub global MERCHANT_ROOT: Field = ${i.opening.merchant_root};`,
    `pub global EXPIRY: u64 = ${i.opening.expiry};`,
    `pub global OPERATOR_ID: Field = ${i.opening.operator_id};`,
    `pub global NONCE: Field = ${i.opening.nonce};`,
    `pub global SALT: Field = ${i.opening.salt};`,
    `pub global SIGNATURE: [u8; 64] = ${bytes(i.assertion.signature)};`,
    `pub global AUTHENTICATOR_DATA: [u8; 37] = ${bytes(i.assertion.authenticator_data)};`,
    `pub global CLIENT_DATA: [u8; ${i.assertion.client_data_json.len}] = ${bytes(i.assertion.client_data_json.storage.slice(0, Number(i.assertion.client_data_json.len)))};`,
    `pub global CHALLENGE_INDEX: u32 = ${i.assertion.challenge_index};`,
    `pub global TYPE_INDEX: u32 = ${i.assertion.type_index};`,
  ];
  return `${lines.join("\n")}\n`;
}

const vectors: Record<string, unknown> = {};
for (const [capture, file] of [
  ["payment", "Prover_payment.toml"],
  ["webauthn", "Prover_webauthn.toml"],
] as const) {
  const assertion = signed(capture);
  const { inputs, statement } = await c3Inputs({ mandate: m, salt, payloadSd, assertion, users });
  writeFileSync(resolve(circuit, file), `${toml(inputs).join("\n")}\n`);
  if (capture === "payment") writeFileSync(resolve(circuit, "src/vectors.nr"), noirVectors(inputs));
  vectors[capture] = {
    assertion,
    statement: Object.fromEntries(
      Object.entries(statement).map(([k, x]) => [k, `0x${x.toString(16)}`]),
    ),
  };
}

writeFileSync(
  resolve(here, "../test/vectors/c3.json"),
  `${JSON.stringify(
    {
      mandate: m,
      salt: b64u(salt),
      payloadSd,
      disclosures,
      // COSE_Key of the test passkey, standard base64, as the passkey table stores it.
      publicKey: Buffer.concat([
        Buffer.from("a5010203262001215820", "hex"),
        point.subarray(1, 33),
        Buffer.from("225820", "hex"),
        point.subarray(33),
      ]).toString("base64"),
      users: users.leaves.map((x) => `0x${x.toString(16)}`),
      ...vectors,
    },
    null,
    2,
  )}\n`,
);

writeFileSync(
  resolve(here, "../../../circuits/c1/Prover_anonymous.toml"),
  c1Toml(await c1Inputs(m, salt)),
);
