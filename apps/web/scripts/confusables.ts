/**
 * Writes `lib/confusables.generated.ts`: the mappings of Unicode's confusables data (UTS #39 section 4)
 * from a non-ASCII character to an ASCII prototype, the ones that make a name pass for a Latin
 * one. The data file is pinned by version and SHA-256.
 *
 * Run: node apps/web/scripts/confusables.ts
 */
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const VERSION = "17.0.0";
const URL_ = `https://www.unicode.org/Public/${VERSION}/security/confusables.txt`;
const SHA256 = "091c7f82fc39ef208faf8f94d29c244de99254675e09de163160c810d13ef22a";

const res = await fetch(URL_);
if (!res.ok) throw new Error(`${URL_} answered ${res.status}`);
const bytes = new Uint8Array(await res.arrayBuffer());
const digest = createHash("sha256").update(bytes).digest("hex");
if (digest !== SHA256) throw new Error(`confusables.txt ${VERSION} hashes to ${digest}`);

const ascii = (s: string) => [...s].every((c) => (c.codePointAt(0) as number) < 0x80);
const chars = (field: string) =>
  String.fromCodePoint(
    ...field
      .trim()
      .split(/\s+/)
      .map((h) => Number.parseInt(h, 16)),
  );
const map: Record<string, string> = {};
for (const line of new TextDecoder().decode(bytes).split("\n")) {
  const data = line.split("#")[0]?.trim();
  if (!data) continue;
  const [source = "", target = ""] = data.split(";");
  const from = chars(source);
  const to = chars(target);
  if (!ascii(from) && ascii(to)) map[from] = to;
}

// Escaped, so the source holds no invisible or bidirectional characters.
const quoted = (t: string) =>
  JSON.stringify(t).replace(
    /[^\x20-\x7e]/gu,
    (c) => `\\u{${(c.codePointAt(0) as number).toString(16)}}`,
  );
const entries = Object.entries(map)
  .map(([from, to]) => `  ${quoted(from)}: ${quoted(to)},`)
  .join("\n");
const out = fileURLToPath(new URL("../lib/confusables.generated.ts", import.meta.url));
writeFileSync(
  out,
  `// Generated by scripts/confusables.ts from Unicode confusables.txt ${VERSION}. Do not edit.\n\n/** Non-ASCII character to the ASCII it can pass for (UTS #39 section 4). */\nexport const CONFUSABLES: Readonly<Record<string, string>> = {\n${entries}\n};\n`,
);
console.log(`${Object.keys(map).length} mappings written to ${out}`);
