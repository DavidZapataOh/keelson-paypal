#!/bin/sh
# Regenerates every artboard, builds the shared .riv, publishes it to the site and
# stamps its version so browsers fetch the new file.
set -e
cd "$(dirname "$0")"
for f in tools/build_*.py; do (cd tools && PYTHONDONTWRITEBYTECODE=1 python3 "$(basename "$f")"); done
rive landing --once
cp landing/build/keelson-landing.riv ../public/rive/landing.riv
VERSION=$(shasum -a 256 ../public/rive/landing.riv | cut -c1-12)
printf '// Generated by rive/build.sh from the published file. Do not edit.\nexport const RIVE_VERSION = "%s";\n' "$VERSION" > ../src/rive-version.ts
echo "published public/rive/landing.riv ($VERSION)"
