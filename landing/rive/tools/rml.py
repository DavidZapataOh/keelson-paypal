"""Small helpers for writing Rive RML by hand.

Every section of the landing is one artboard in rive/landing/, generated by its
own build_<section>.py. All artboards share the fonts declared in fonts.rml.

Draw order: in RML the first element declared paints on top. Helpers that take
a list of children expect it back-to-front (background first) and reverse it.
"""

