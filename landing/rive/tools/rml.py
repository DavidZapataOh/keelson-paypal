class Ids:
    """Hands out ids in a range of its own, so artboards never collide."""

    def __init__(self, start: int):
        self.n = start

    def __call__(self) -> str:
        self.n += 1
        return f"0:{self.n}"


class Builder:
    def __init__(self, id_start: int):
        self.nid = Ids(id_start)

    # ------------------------------------------------------------ text
    def style(self, name, size, color, weight=None, font=MONO):
        sid = self.nid()
        axis = f'<TextStyleAxis tag="2003265652" axisValue="{weight}" name="Weight"/>' if weight else ""
        family = "Geist Mono" if font == MONO else "Instrument Sans"
        return sid, (
            f'<TextStylePaint fontSize="{size}" fontAssetId="{font}" familyName="{family}" '
            f'styleName="Regular" name="{name}" id="{sid}">'
            f'<Fill name="Fill"><SolidColor colorValue="{color}" name="C"/></Fill>{axis}'
            f"</TextStylePaint>"
        )

    def text(self, x, y, value, size, color, weight=None, font=MONO, ox=0.0, opacity=1, tid=None):
        """A Text owns its style, so every text gets a fresh one."""
        tid = tid or self.nid()
        sid, sxml = self.style(f"S {value[:12]}", size, color, weight, font)
        return tid, (
            f'<Text x="{x}" y="{y}" originX="{ox}" originY="0.5" sizingValue="autoWidth" '
            f'opacity="{opacity}" name="T {value[:18]}" id="{tid}">{sxml}'
            f'<TextValueRun styleId="{sid}" text="{value}" name="Run"/></Text>'
        )

    # ------------------------------------------------------------ shapes
    @staticmethod
    def paint(fill=None, stroke=None, thick=1.5, dash=None, gradient=None, trim=None, cap="round"):
        out = ""
        if fill:
            out += f'<Fill name="Fill"><SolidColor colorValue="{fill}" name="C"/></Fill>'
        if gradient:
            stops = "".join(f'<GradientStop colorValue="{c}" position="{p}"/>' for c, p in gradient["stops"])
            out += (
                f'<Fill name="Fill"><LinearGradient startX="{gradient["sx"]}" startY="{gradient["sy"]}" '
                f'endX="{gradient["ex"]}" endY="{gradient["ey"]}" name="G">{stops}</LinearGradient></Fill>'
            )
        if stroke:
            extra = ""
            if dash:
                extra += f'<DashPath name="Dashes"><Dash length="{dash[0]}" name="On"/><Dash length="{dash[1]}" name="Off"/></DashPath>'
            if trim:
                tid, start, end = trim
                extra += f'<TrimPath start="{start}" end="{end}" name="Trim" id="{tid}"/>'
            out += (
                f'<Stroke thickness="{thick}" cap="{cap}" join="round" name="Stroke">'
                f'<SolidColor colorValue="{stroke}" name="C"/>{extra}</Stroke>'
            )
        return out

    def rect(self, x, y, w, h, r=0, ox=0.5, oy=0.5, sid=None, opacity=1, name=None, **p):
        sid = sid or self.nid()
        corners = f'cornerRadiusTL="{r}" cornerRadiusTR="{r}" cornerRadiusBL="{r}" cornerRadiusBR="{r}"' if r else ""
        return sid, (
            f'<Shape x="{x}" y="{y}" opacity="{opacity}" name="{name or "R" + sid}" id="{sid}">'
            f'<Rectangle width="{w}" height="{h}" originX="{ox}" originY="{oy}" {corners} name="Path"/>'
            f"{self.paint(**p)}</Shape>"
        )

    def ellipse(self, x, y, d, sid=None, opacity=1, name=None, sx=1, sy=1, **p):
        sid = sid or self.nid()
        return sid, (
            f'<Shape x="{x}" y="{y}" opacity="{opacity}" scaleX="{sx}" scaleY="{sy}" name="{name or "E" + sid}" id="{sid}">'
            f'<Ellipse width="{d}" height="{d}" name="Path"/>{self.paint(**p)}</Shape>'
        )

    def poly(self, points, x=0, y=0, closed=True, sid=None, opacity=1, name=None, **p):
        sid = sid or self.nid()
        verts = "".join(f'<StraightVertex x="{px}" y="{py}"/>' for px, py in points)
        cl = 'isClosed="true" isClockwise="true"' if closed else 'isClosed="false"'
        return sid, (
            f'<Shape x="{x}" y="{y}" opacity="{opacity}" name="{name or "P" + sid}" id="{sid}">'
            f'<PointsPath {cl} name="Path">{verts}</PointsPath>{self.paint(**p)}</Shape>'
        )

    def line(self, x1, y1, x2, y2, **p):
        return self.poly([(x1, y1), (x2, y2)], closed=False, **p)

    def node(self, x, y, children, sid=None, opacity=1, rotation=0, name=None, sx=1, sy=1):
        sid = sid or self.nid()
        inner = "".join(reversed(children))
        return sid, (
            f'<Node x="{x}" y="{y}" opacity="{opacity}" rotation="{rotation}" scaleX="{sx}" scaleY="{sy}" '
            f'name="{name or "N" + sid}" id="{sid}">{inner}</Node>'
        )

    def check_mark(self, color, size=1.0):
        s = size
        return (
            f'<Shape name="Check"><PointsPath isClosed="false" name="Path">'
            f'<StraightVertex x="{-4.5*s}" y="{0.5*s}"/><StraightVertex x="{-1.5*s}" y="{3.8*s}"/>'
            f'<StraightVertex x="{4.8*s}" y="{-3.6*s}"/></PointsPath>'
            f'<Stroke thickness="2" cap="round" join="round" name="S"><SolidColor colorValue="{color}" name="C"/></Stroke></Shape>'
        )

    def cross_mark(self, color, size=1.0):
        s = size
        return (
            f'<Shape name="Cross"><PointsPath isClosed="false" name="Path"><StraightVertex x="{-4*s}" y="{-4*s}"/><StraightVertex x="{4*s}" y="{4*s}"/></PointsPath>'
            f'<PointsPath isClosed="false" name="Path 2"><StraightVertex x="{4*s}" y="{-4*s}"/><StraightVertex x="{-4*s}" y="{4*s}"/></PointsPath>'
            f'<Stroke thickness="2" cap="round" name="S"><SolidColor colorValue="{color}" name="C"/></Stroke></Shape>'
        )


class Timeline:
    """Keyframes for one LinearAnimation. Every property touched by any timeline of
    the artboard is keyed at frame 0 here too (from `defaults`), so entering a
    state always starts from a known pose."""

    def __init__(self, defaults: dict):
        self.defaults = defaults
        self.tracks = {}

    def key(self, obj, prop, frames, ease=None):
        self.tracks[(obj, prop)] = [(f, v, ease) for f, v in frames]
        return self

    def fade(self, obj, at, to, dur=10, ease=EASE_OUT):
        start = self.defaults.get((obj, OP), 1)
        return self.key(obj, OP, [(0, start), (at, start), (at + dur, to)], ease)

    def slide_in(self, obj, at, y, dist=12, dur=16):
        self.key(obj, OP, [(0, 0), (at, 0), (at + dur * 0.7, 1)], EASE_OUT)
        return self.key(obj, Y, [(0, y + dist), (at, y + dist), (at + dur, y)], EASE_OUT)

    def slide_out(self, obj, at, y, dist=12, dur=12):
        self.key(obj, OP, [(0, 1), (at, 1), (at + dur, 0)], EASE_OUT)
        return self.key(obj, Y, [(0, y), (at, y), (at + dur, y - dist)], EASE_OUT)

    def pop(self, obj, at, peak=1.0, start=0.4, dur=18, ease=BACK):
        self.key(obj, OP, [(0, 0), (at, 0), (at + 6, 1)])
        self.key(obj, SX, [(0, start), (at, start), (at + dur, peak)], ease)
        return self.key(obj, SY, [(0, start), (at, start), (at + dur, peak)], ease)

    def xml(self, name, aid, duration, loop="oneShot"):
        for k, v in self.defaults.items():
            self.tracks.setdefault(k, [(0, v, None)])
        objs = {}
        for (obj, prop), frames in self.tracks.items():
            kfs = []
            for f, v, ease in frames:
                if ease:
                    kfs.append(f'<KeyFrameDouble value="{v}" frame="{int(round(f))}" interpolationType="cubic">{ease}</KeyFrameDouble>')
                else:
                    kfs.append(f'<KeyFrameDouble value="{v}" frame="{int(round(f))}" interpolationType="linear"/>')
            objs.setdefault(obj, []).append(f'<KeyedProperty propertyKey="{prop}">{"".join(kfs)}</KeyedProperty>')
        body = "".join(f'<KeyedObject objectId="{o}">{"".join(ps)}</KeyedObject>' for o, ps in objs.items())
        return f'<LinearAnimation loopValue="{loop}" duration="{int(duration)}" name="{name}" id="{aid}">{body}</LinearAnimation>'


def bool_condition(vm, prop, value):
    return (
        '<TransitionViewModelCondition opValue="equal">'
        "<TransitionPropertyViewModelComparator><BindablePropertyBoolean>"
        f'<DataBindContext sourcePathIds="{vm}-{prop}" propertyKey="634"/>'
        "</BindablePropertyBoolean></TransitionPropertyViewModelComparator>"
        f'<TransitionValueBooleanComparator value="{"true" if value else "false"}"/>'
        "</TransitionViewModelCondition>"
    )


def number_condition(vm, prop, value):
    return (
        '<TransitionViewModelCondition opValue="equal">'
        "<TransitionPropertyViewModelComparator><BindablePropertyNumber>"
        f'<DataBindContext sourcePathIds="{vm}-{prop}" propertyKey="636"/>'
        "</BindablePropertyNumber></TransitionPropertyViewModelComparator>"
        f'<TransitionValueNumberComparator value="{value}"/>'
        "</TransitionViewModelCondition>"
    )


def write(name: str, body: str):
    out = LANDING / f"{name}.rml"
    out.write_text(f'<Rive version="1" kind="fragment">\n{body}\n</Rive>\n')
    print(f"wrote {out}")
