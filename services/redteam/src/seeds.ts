/** The share of templates held out: attacked, but never fed back to the mutator. @internal */
export const HOLDOUT_SHARE = 0.2;

/** SHA-256 of a template's id, text and placements, as recorded in the ledger. */
export function templateHash(t: Template): string {
  return createHash("sha256")
    .update(JSON.stringify([t.id, t.class, t.source, t.text, t.placements]))
    .digest("hex");
}

/**
 * The held-out template ids: the first fifth of the templates ordered by hash, a split fixed by
 * the templates themselves rather than by any result.
 */
export function holdout(templates: readonly Template[] = TEMPLATES): Set<string> {
  const ordered = [...templates].sort((a, b) =>
    templateHash(a) < templateHash(b) ? -1 : templateHash(a) > templateHash(b) ? 1 : 0,
  );
  return new Set(ordered.slice(0, Math.ceil(templates.length * HOLDOUT_SHARE)).map((t) => t.id));
}

/** The template's text with `{target}` resolved on the store. */
export function render(text: string, cls: AttackClass, storeOrigin: string): string {
  return text.replaceAll("{target}", new URL(TARGETS[cls], storeOrigin).href);
}
